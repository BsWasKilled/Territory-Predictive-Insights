package persistencia;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.SQLException;

import excecao.PersistenciaException;

/**
 * Sabe como chegar ao banco de dados e como criar as tabelas. Os DAOs pedem
 * uma conexão aqui a cada operação e a fecham em seguida (try-with-resources),
 * então nenhuma conexão fica esquecida aberta.
 */
public class ConexaoBanco {

    /** Propriedade que troca o banco sem mexer no código: java -Dbanco.url=... */
    public static final String PROPRIEDADE_URL = "banco.url";

    /**
     * Banco H2 embarcado, gravado em arquivo na pasta "dados" (criada sozinha
     * na primeira execução). É por estar em arquivo que o histórico sobrevive
     * ao fim do programa.
     *
     * DB_CLOSE_DELAY=-1 mantém o banco aberto enquanto o programa roda, em vez
     * de abrir e fechar o arquivo a cada operação dos DAOs; o próprio H2 fecha
     * o banco quando o programa termina.
     */
    public static final String URL_PADRAO = "jdbc:h2:file:./dados/territorio;DB_CLOSE_DELAY=-1";

    private static final String USUARIO_PADRAO = "sa";
    private static final String SENHA_PADRAO = "";

    private static final String SQL_CRIAR_TABELA_MEDICAO = """
            CREATE TABLE IF NOT EXISTS medicao (
                id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                codigo_sensor VARCHAR(40)      NOT NULL,
                tipo_sensor   VARCHAR(40)      NOT NULL,
                valor         DOUBLE PRECISION NOT NULL,
                data_hora     TIMESTAMP        NOT NULL
            )
            """;

    private static final String SQL_CRIAR_INDICE_MEDICAO = """
            CREATE INDEX IF NOT EXISTS idx_medicao_sensor
                ON medicao (codigo_sensor, data_hora)
            """;

    private static final String SQL_CRIAR_TABELA_ALERTA = """
            CREATE TABLE IF NOT EXISTS alerta (
                id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                codigo_sensor     VARCHAR(40)      NOT NULL,
                tipo_sensor       VARCHAR(40)      NOT NULL,
                nivel             VARCHAR(20)      NOT NULL,
                estrategia        VARCHAR(80)      NOT NULL,
                valor_previsto    DOUBLE PRECISION NOT NULL,
                limite_estourado  DOUBLE PRECISION NOT NULL,
                id_ultima_medicao BIGINT           NOT NULL REFERENCES medicao (id),
                data_hora         TIMESTAMP        NOT NULL
            )
            """;

    private final String url;
    private final String usuario;
    private final String senha;

    public ConexaoBanco(String url, String usuario, String senha) {
        this.url = url;
        this.usuario = usuario;
        this.senha = senha;
    }

    /**
     * Conexão usada pelo programa: o banco em arquivo, a menos que outro
     * endereço seja informado na propriedade "banco.url" (por exemplo, o H2
     * em memória para uma execução que não deixa nada gravado).
     */
    public static ConexaoBanco padrao() {
        return new ConexaoBanco(System.getProperty(PROPRIEDADE_URL, URL_PADRAO), USUARIO_PADRAO, SENHA_PADRAO);
    }

    public String getUrl() {
        return url;
    }

    /** Abre uma conexão nova. Quem chama deve fechá-la, de preferência com try-with-resources. */
    public Connection abrir() throws SQLException {
        return DriverManager.getConnection(url, usuario, senha);
    }

    /** Cria as tabelas na primeira execução; nas seguintes, mantém o que já está gravado. */
    public void prepararBanco() {
        try (Connection conexao = abrir()) {
            executar(conexao, SQL_CRIAR_TABELA_MEDICAO);
            executar(conexao, SQL_CRIAR_INDICE_MEDICAO);
            executar(conexao, SQL_CRIAR_TABELA_ALERTA);
        } catch (SQLException e) {
            throw new PersistenciaException("não foi possível preparar o banco de dados em " + url, e);
        }
    }

    /** Executa um comando SQL fixo (sem parâmetros) e fecha o PreparedStatement em seguida. */
    private static void executar(Connection conexao, String sql) throws SQLException {
        try (PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.execute();
        }
    }
}
